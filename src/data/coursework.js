export const courseworkItems = courseworkSections.flatMap(section => section.groups.flatMap(group => group.items))
export function courseworkProgress(marks, items = courseworkItems) {
  const done = items.filter(item => marks[item.id] === true).length
  return {done,total:items.length,percent:items.length ? Math.round(done/items.length*100) : 0}
}
