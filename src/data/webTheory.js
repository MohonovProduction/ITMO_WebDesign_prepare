function toTopic(trackId, title, index) {
  const track = TRACKS.find((item) => item.id === trackId)
  return {
    id: `${trackId}-${index + 1}`,
    trackId,
    number: index + 1,
    title,
    status: 'planned',
    answerPlan: ['Определение', 'Зачем это нужно', 'Процесс или устройство', 'Пример', 'Типичные ошибки и связи'],
    track,
  }
}

export const webTheory = [
  ...techTopics.map((title, index) => toTopic('tech', title, index)),
  ...uxTopics.map((title, index) => toTopic('ux', title, index)),
]

export function topicsByTrack(trackId) {
  return webTheory.filter((topic) => topic.trackId === trackId)
}
